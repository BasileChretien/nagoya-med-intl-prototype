/**
 * Everything that makes a version fall behind another, in one list, for both `npm run check`
 * (check-staleness.mjs) and `npm run sync -- status`, so the two always report the same things:
 *   - an English or Japanese page changed without its counterpart (versions-in-step)
 *   - a bilingual field changed in one language only, or given in one language only (versions-in-step)
 *   - a fact states different numbers in its two languages (facts-match)
 *   - a report translation was made from an older version of its original (translations-current)
 *   - the faculty texts in faculty/ no longer match what the data produces (faculty-texts)
 */
import { readFileSync, readdirSync, existsSync } from 'node:fs';
import { join } from 'node:path';
import { SYNC_FILE, pagePairs, scanData, readRegistry, comparePages, compareFields, compareNumbers, compareReports } from './staleness-lib.mjs';
import { buildFacultyTexts } from './build-faculty-texts.mjs';

const lf = (s) => s.replace(/\r\n/g, '\n');

/** @param {string} root @returns {{ errors: string[], pageCount: number, fieldCount: number }} */
export function staleness(root) {
  const errors = [];
  const registry = readRegistry(root);
  const pages = pagePairs(root);
  const { fields, halves } = scanData(root);
  if (!registry) errors.push(`${SYNC_FILE} is missing: run "npm run sync -- adopt" once`);
  else {
    errors.push(...comparePages(pages, registry.pages));
    errors.push(...compareFields(fields, registry.fields));
  }
  errors.push(...halves);
  errors.push(...compareNumbers(fields));
  errors.push(...compareReports(root));

  const expected = buildFacultyTexts(root);
  const facultyDir = join(root, 'faculty');
  for (const [name, content] of Object.entries(expected)) {
    const file = join(facultyDir, name);
    if (!existsSync(file) || lf(readFileSync(file, 'utf8')) !== content) errors.push(`faculty/${name} is out of date: run "npm run faculty-texts"`);
  }
  if (existsSync(facultyDir)) {
    for (const name of readdirSync(facultyDir)) {
      if (name.endsWith('.md') && !expected[name]) errors.push(`faculty/${name} is not generated by scripts/build-faculty-texts.mjs: remove it or add it to the generator`);
    }
  }
  return { errors, pageCount: Object.keys(pages).length, fieldCount: Object.keys(fields).length };
}
