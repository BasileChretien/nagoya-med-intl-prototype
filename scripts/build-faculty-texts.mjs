#!/usr/bin/env node
/**
 * Build the texts the faculty's web team puts on the faculty website (the "faculty layer"), from the site's data.
 * Because they are generated, they cannot say something the site does not; check-staleness.mjs fails when the
 * files in faculty/ fall behind the data.
 *
 *   npm run faculty-texts      write faculty/*.md
 */
import { readFileSync, writeFileSync, mkdirSync, readdirSync, existsSync } from 'node:fs';
import { join } from 'node:path';
import { fileURLToPath } from 'node:url';

const SECTION_ORDER = ['study-in-nagoya', 'study-abroad', 'degrees'];

const T = {
  en: {
    // The faculty's own title for the page, naming the office and its department as the Japanese does.
    unitsTitle: 'Office of International Affairs (Department of International Medical Education)',
    site: 'International website',
    directory: 'Team, research and publications',
    contact: 'Contact',
    email: 'Email: ', phone: 'Phone: ',
    intlTitle: 'International',
    intlLead: 'The Office of International Affairs runs the international programmes of the School of Medicine. Full information, deadlines and how to apply are on the international website.',
    open: 'Open the international website',
    programme: 'Programme', who: 'Who it is for',
    alsoTitle: 'Also on the international website',
    stories: 'Student stories', news: 'News and events', partnerships: 'Partnerships',
    entry: (url) => `International programmes, deadlines, student stories and news of the Office of International Affairs are on the [international website](${url}).`,
  },
  ja: {
    unitsTitle: '国際医学教育学・国際連携室',
    site: '国際交流のサイト',
    directory: '教職員、研究、業績',
    contact: '問い合わせ先',
    email: 'メール：', phone: '電話：',
    intlTitle: '国際交流',
    intlLead: '国際連携室は医学部の国際プログラムを運営しています。詳しい内容、締切、応募方法は国際交流のサイトに載せています。',
    open: '国際交流のサイトを開く',
    programme: 'プログラム', who: '対象',
    alsoTitle: '国際交流のサイトにあるそのほかの情報',
    stories: '体験記', news: 'お知らせ・イベント', partnerships: '国際連携',
    entry: (url) => `国際連携室のプログラムと締切、体験記やお知らせは、[国際交流のサイト](${url})に載せています。`,
  },
};

function readJson(root, rel) { return JSON.parse(readFileSync(join(root, rel), 'utf8')); }

/** The "summary:" line of a page's front matter. */
function summaryOf(root, lang, slugPath) {
  const text = readFileSync(join(root, 'src', 'content', 'pages', lang, `${slugPath}.md`), 'utf8');
  const m = text.match(/^summary:\s*(.+)$/m);
  return m ? m[1].trim().replace(/^["']|["']$/g, '') : '';
}

/** @returns {Record<string, string>} file name in faculty/ -> content */
export function buildFacultyTexts(root) {
  const faculty = readJson(root, 'src/data/faculty.json');
  const sections = readJson(root, 'src/i18n/sections.json');
  const contacts = readJson(root, 'src/data/contacts.json');
  const office = contacts.find((c) => c.id === 'intl-office');
  const progDir = join(root, 'src', 'data', 'programmes');
  const programmes = readdirSync(progDir).filter((n) => n.endsWith('.json')).sort()
    .map((n) => ({ id: n.replace(/\.json$/, ''), ...JSON.parse(readFileSync(join(progDir, n), 'utf8')) }));
  const site = (lang, path = '') => `${faculty.site.production}${lang}/${path ? `${path.replace(/\/?$/, '/')}` : ''}`;
  const cell = (s) => s.replace(/\|/g, '\\|').replace(/\s+/g, ' ').trim();

  const files = {};
  files['README.md'] = [
    '# Texts for the faculty website',
    '',
    '<!-- Generated by scripts/build-faculty-texts.mjs from the site data. Do not edit by hand: change the data, then run `npm run faculty-texts`. -->',
    '',
    'These texts are for the faculty\'s web team. They are generated from the international site\'s own data, so the faculty pages and the site say the same thing. The content check fails when they fall behind the data.',
    '',
    '| File | Where it goes on the faculty website |',
    '| --- | --- |',
    `| \`units-page.en.md\`, \`units-page.ja.md\` | The office\'s page in the list of units: ${faculty.pages.units.en} and ${faculty.pages.units.ja} |`,
    `| \`international-section.en.md\`, \`international-section.ja.md\` | The International section, as a gateway to the international site: ${faculty.pages.international.en} and ${faculty.pages.international.ja} |`,
    `| \`directory-entry.en.md\`, \`directory-entry.ja.md\` | One paragraph to add to the department\'s laboratory directory entry: ${faculty.pages.directory.en} and ${faculty.pages.directory.ja} |`,
    '',
    `**When to send them.** Their links use the new site's addresses (${site('en')}… and ${site('ja')}…), which exist only once the new site is published at ${faculty.site.production}. Send the texts with that launch, not before: until then, those links lead nowhere. After the launch, send each file again when it changes.`,
    '',
    'A weekly check (`npm run check:faculty`, `.github/workflows/faculty-drift.yml`) compares the live faculty pages with the site.',
    '',
  ].join('\n');

  for (const lang of ['en', 'ja']) {
    const t = T[lang];
    files[`units-page.${lang}.md`] = [
      `# ${t.unitsTitle}`,
      '',
      summaryOf(root, lang, 'about/index'),
      '',
      `- [${t.site}](${site(lang)})`,
      `- [${t.directory}](${faculty.pages.directory[lang]})`,
      '',
      `## ${t.contact}`,
      '',
      `- ${t.email}${office.email}`,
      ...(office.phone ? [`- ${t.phone}${office.phone}`] : []),
      '',
    ].join('\n');

    const body = [`# ${t.intlTitle}`, '', t.intlLead, '', `[${t.open}](${site(lang)})`, ''];
    for (const s of SECTION_ORDER) {
      const list = programmes.filter((p) => p.section === s);
      if (!list.length) continue;
      body.push(`## [${sections[lang][s]}](${site(lang, s)})`, '', `| ${t.programme} | ${t.who} |`, '| --- | --- |');
      for (const p of list) body.push(`| [${cell(p.name[lang])}](${site(lang, p.page)}) | ${cell(p.audience[lang])} |`);
      body.push('');
    }
    body.push(`## ${t.alsoTitle}`, '',
      `- [${t.stories}](${site(lang, 'stories')})`,
      `- [${t.news}](${site(lang, 'news')})`,
      `- [${t.partnerships}](${site(lang, 'partnerships')})`,
      `- ${t.email}${office.email}`, '');
    files[`international-section.${lang}.md`] = body.join('\n');

    files[`directory-entry.${lang}.md`] = `${t.entry(site(lang))}\n`;
  }
  return files;
}

if (process.argv[1] && fileURLToPath(import.meta.url) === process.argv[1]) {
  const root = fileURLToPath(new URL('..', import.meta.url));
  const out = join(root, 'faculty');
  if (!existsSync(out)) mkdirSync(out);
  const files = buildFacultyTexts(root);
  for (const [name, content] of Object.entries(files)) writeFileSync(join(out, name), content);
  process.stdout.write(`wrote ${Object.keys(files).length} files to faculty/\n`);
}
